from typing import Optional, Dict, Any
from pydantic import BaseModel, Field
import time

class GenerationRequest(BaseModel):
    prompt: str = Field(
        ...,
        min_length=1,
        json_schema_extra={
            "example": "Explain quantum physics in 5-year-old terms."
        }
    )
    max_tokens: int = Field(
        256,
        ge=10,
        le=1024,
        json_schema_extra={
            "example": 128
        }
    )
    temperature: float = Field(
        0.7,
        ge=0.0,
        le=1.0,
        json_schema_extra={
            "example": 0.7
        }
    )

class GenerationResponse(BaseModel):
    result: str
    token_usage: int = Field(..., description="Number of tokens generated by the model")
    cached: bool = Field(False, description="Whether the response was served from cache")
    latency_ms: float = Field(..., description="Inference/request processing latency in milliseconds")

class HealthCheckResponse(BaseModel):
    status: str = Field(..., description="Overall health status: healthy, degraded, initializing, or unhealthy")
    model_loaded: bool = Field(..., description="Whether LLM model is ready in memory")
    redis_connected: bool = Field(..., description="Whether Redis caching container is reachable")
    model_id: str = Field(..., description="Identifier of the active LLM")
    timestamp: float = Field(default_factory=time.time, description="Unix timestamp of healthcheck probe")
    details: Optional[Dict[str, Any]] = Field(default=None, description="Detailed diagnostic metrics")
